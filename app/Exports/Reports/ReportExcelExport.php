<?php

namespace App\Exports\Reports;

use Maatwebsite\Excel\Concerns\FromArray;
use Maatwebsite\Excel\Concerns\ShouldAutoSize;
use Maatwebsite\Excel\Concerns\WithStyles;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;

class ReportExcelExport implements FromArray, ShouldAutoSize, WithStyles
{
    public function __construct(
        private readonly array $report
    ) {
    }

    public function array(): array
    {
        return [
            [$this->report['title']],
            ['Generated At: ' . $this->report['generated_at']],
            ['Date Range: ' . $this->report['period_label']],
            ['Vehicle Status: ' . $this->report['vehicle_status_label']],
            ['Generated By: ' . $this->report['generated_by']],
            [],
            $this->report['headers'],
            ...$this->report['rows'],
        ];
    }

    public function styles(Worksheet $sheet): array
    {
        $lastColumn = $sheet->getHighestColumn();
        $lastRow = $sheet->getHighestRow();

        // Merge report metadata rows across the width of the table.
        for ($row = 1; $row <= 5; $row++) {
            $sheet->mergeCells("A{$row}:{$lastColumn}{$row}");
        }

        $sheet->getStyle("A1:{$lastColumn}1")->applyFromArray([
            'font' => [
                'bold' => true,
                'size' => 18,
                'color' => ['rgb' => 'FFFFFF'],
            ],
            'fill' => [
                'fillType' => 'solid',
                'startColor' => ['rgb' => '1F2937'],
            ],
            'alignment' => [
                'vertical' => 'center',
            ],
        ]);

        $sheet->getRowDimension(1)->setRowHeight(32);

        $sheet->getStyle("A2:{$lastColumn}5")->applyFromArray([
            'font' => [
                'size' => 10,
                'color' => ['rgb' => '374151'],
            ],
        ]);

        // Style the actual table header row (row 7).
        $headerRow = 6;

        $sheet->getStyle("A{$headerRow}:{$lastColumn}{$headerRow}")
            ->applyFromArray([
                'font' => [
                    'bold' => true,
                    'color' => ['rgb' => 'FFFFFF'],
                ],
                'fill' => [
                    'fillType' => 'solid',
                    'startColor' => ['rgb' => '374151'],
                ],
                'alignment' => [
                    'vertical' => 'center',
                    'horizontal' => 'left',
                    'wrapText' => true,
                ],
            ]);

        $sheet->getRowDimension($headerRow)->setRowHeight(30);

        // Style data rows separately, starting at row 8.
        $dataStartRow = $headerRow + 1;

        if ($lastRow >= $dataStartRow) {
            $sheet->getStyle("A{$dataStartRow}:{$lastColumn}{$lastRow}")
                ->getAlignment()
                ->setVertical('center');

            $sheet->getStyle("A{$headerRow}:{$lastColumn}{$lastRow}")
                ->getBorders()
                ->getAllBorders()
                ->setBorderStyle('thin')
                ->getColor()
                ->setRGB('E5E7EB');

            foreach ($this->report['headers'] as $index => $heading) {
                if (str_contains(strtolower($heading), 'cost')) {
                    $column = \PhpOffice\PhpSpreadsheet\Cell\Coordinate::stringFromColumnIndex(
                        $index + 1
                    );

                    $sheet->getStyle("{$column}{$dataStartRow}:{$column}{$lastRow}")
                        ->getNumberFormat()
                        ->setFormatCode('$#,##0.00;[Red]-$#,##0.00');
                }
            }
        }

        // Style the TOTAL row consistently across reports.
        $totalRow = $lastRow;
        $totalLabelFound = false;

        if ($lastRow >= $dataStartRow) {
            for ($columnIndex = 1; $columnIndex <= \PhpOffice\PhpSpreadsheet\Cell\Coordinate::columnIndexFromString($lastColumn); $columnIndex++) {
                $column = \PhpOffice\PhpSpreadsheet\Cell\Coordinate::stringFromColumnIndex($columnIndex);

                if (
                    str_starts_with(
                        strtoupper(trim((string) $sheet->getCell("{$column}{$totalRow}")->getValue())),
                        'TOTAL'
                    )
                ) {
                    $totalLabelFound = true;
                    break;
                }
            }
        }

        if ($totalLabelFound) {
            $sheet->getStyle("A{$totalRow}:{$lastColumn}{$totalRow}")
                ->applyFromArray([
                    'font' => [
                        'bold' => true,
                        'color' => ['rgb' => '1F2937'],
                    ],
                    'fill' => [
                        'fillType' => 'solid',
                        'startColor' => ['rgb' => 'F3F4F6'],
                    ],
                    'alignment' => [
                        'vertical' => 'center',
                    ],
                    'borders' => [
                        'top' => [
                            'borderStyle' => \PhpOffice\PhpSpreadsheet\Style\Border::BORDER_MEDIUM,
                            'color' => ['rgb' => '9CA3AF'],
                        ],
                    ],
                ]);

            $sheet->getRowDimension($totalRow)->setRowHeight(24);
        }

        $sheet->setAutoFilter("A{$headerRow}:{$lastColumn}{$lastRow}");
        $sheet->freezePane('A' . $dataStartRow);

        return [];

    }
}